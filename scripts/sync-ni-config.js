/**
 * Sync assets/js/ni/config.js from .env.local (XAMPP-friendly public client config).
 * Usage: node scripts/sync-ni-config.js
 */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const envPath = path.join(root, '.env.local');
const outPath = path.join(root, 'assets', 'js', 'ni', 'config.js');

if (!fs.existsSync(envPath)) {
  console.error('Missing .env.local — copy .env.example and fill INSFORGE_URL / INSFORGE_ANON_KEY');
  process.exit(1);
}

const env = Object.fromEntries(
  fs
    .readFileSync(envPath, 'utf8')
    .split(/\r?\n/)
    .filter((line) => line && !line.trim().startsWith('#') && line.includes('='))
    .map((line) => {
      const i = line.indexOf('=');
      return [line.slice(0, i).trim(), line.slice(i + 1).trim()];
    })
);

const baseUrl = env.INSFORGE_URL || env.NEXT_PUBLIC_INSFORGE_URL;
const anonKey = env.INSFORGE_ANON_KEY || env.NEXT_PUBLIC_INSFORGE_ANON_KEY;

if (!baseUrl || !anonKey) {
  console.error('INSFORGE_URL and INSFORGE_ANON_KEY are required in .env.local');
  process.exit(1);
}

const contents = `/**
 * Auto-generated by scripts/sync-ni-config.js — do not commit secrets beyond the public anon key.
 * Source: .env.local
 */
export const NI_CONFIG = {
  baseUrl: ${JSON.stringify(baseUrl)},
  anonKey: ${JSON.stringify(anonKey)},
};
`;

fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, contents);
console.log('Wrote', outPath);
